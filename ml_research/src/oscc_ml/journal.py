"""TRAINING_JOURNAL.md: a plain-English account of what happened, written ONLY from saved files.

Three journals, each regenerated (overwritten) after the step that changes its inputs:

* ``<run>/TRAINING_JOURNAL.md`` after training (and again after ``evaluate``): reads
  ``run_info.json``, ``metrics.json``, ``train_log.csv``, ``observations/epochs.jsonl``,
  ``observations/training_summary.json`` and, once it exists, ``evaluation.json``;
* ``<runs>/sweep/TRAINING_JOURNAL.md`` after the sweep: reads ``sweep/chosen_lr.json``;
* ``<runs>/TRAINING_JOURNAL.md`` after the sweep, ``train-all`` and ``evaluate``: reads
  ``decisions.jsonl``, ``sweep/chosen_lr.json`` and every run's ``evaluation.json``.

No number is computed here beyond formatting and simple counts of logged rows: every value is copied
from a file, and each section names the file it came from. A missing file gives the sentence
"not yet run" / "not recorded", never a placeholder number. Journals are ordinary files, so
``pack-results`` ships them in ``results_small.zip``.
"""

from __future__ import annotations

import csv
import json
import logging
from pathlib import Path
from typing import Any

logger = logging.getLogger("oscc_ml.journal")

JOURNAL_FILE = "TRAINING_JOURNAL.md"
SWEEP_DIR = "sweep"
HEADER_NOTE = (
    "_Generated by `oscc_ml.journal` from the files named in each section; do not edit by hand. "
    "It is regenerated after every sweep, training run and evaluation._"
)


def _read_json(path: Path) -> dict[str, Any] | None:
    if not path.is_file():
        return None
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    return value if isinstance(value, dict) else None


def _read_jsonl(path: Path) -> list[dict[str, Any]]:
    if not path.is_file():
        return []
    out = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            try:
                out.append(json.loads(line))
            except ValueError:
                continue
    return out


def _read_csv(path: Path) -> list[dict[str, str]]:
    if not path.is_file():
        return []
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def _num(value: Any, digits: int = 4) -> str:
    if value is None or value == "":
        return "n/a"
    try:
        number = float(value)
    except (TypeError, ValueError):
        return str(value)
    if number.is_integer() and abs(number) < 1e15 and digits == 0:
        return str(int(number))
    return f"{number:.{digits}f}"


def _lr(value: Any) -> str:
    try:
        return f"{float(value):g}"
    except (TypeError, ValueError):
        return str(value)


def _duration(seconds: Any) -> str:
    try:
        total = float(seconds)
    except (TypeError, ValueError):
        return "n/a"
    hours, rest = divmod(round(total), 3600)
    minutes, secs = divmod(rest, 60)
    return f"{hours} h {minutes:02d} min {secs:02d} s" if hours else f"{minutes} min {secs:02d} s"


def _ci(block: dict[str, Any] | None) -> str:
    if not block or block.get("estimate") is None:
        return "n/a"
    low, high = _num(block.get("ci_low")), _num(block.get("ci_high"))
    return f"{_num(block['estimate'])} (95% CI {low}-{high})"


def _write(path: Path, lines: list[str]) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    return path


# --------------------------------------------------------------------------------------------------
# One run (training, then evaluation)
# --------------------------------------------------------------------------------------------------


def run_journal_lines(run_dir: Path) -> list[str]:
    info = _read_json(run_dir / "run_info.json") or {}
    metrics = _read_json(run_dir / "metrics.json")
    summary = _read_json(run_dir / "observations" / "training_summary.json")
    epochs = _read_jsonl(run_dir / "observations" / "epochs.jsonl")
    log = _read_csv(run_dir / "train_log.csv")
    evaluation = _read_json(run_dir / "evaluation.json")

    name = info.get("display_name") or info.get("architecture", run_dir.name)
    lines = [f"# Training journal: {name}, seed {info.get('seed', 'n/a')}", "", HEADER_NOTE, ""]

    lines += ["## What was run", "", "_Source: `run_info.json`._", ""]
    if not info:
        lines += ["`run_info.json` is missing, so nothing is known about this run.", ""]
    else:
        lines += [
            f"- Run folder: `{run_dir.name}`; purpose: {info.get('purpose', 'n/a')}; "
            f"status: **{info.get('status', 'n/a')}**.",
            f"- Model: {name} ({info.get('family', 'n/a')}), "
            f"weights: {info.get('weights', 'n/a')}.",
            (
                f"- Tabular model: feature set {info.get('feature_set', 'n/a')} "
                f"({info.get('n_features', 'n/a')} columns), features version "
                f"{info.get('tabular_features_version', 'n/a')}, table SHA-256 "
                f"`{str(info.get('features_sha256', 'n/a'))[:16]}…`."
                if info.get("model_type") == "tabular"
                else f"- Learning rate {_lr(info.get('lr'))} (source: "
                f"{info.get('lr_source', 'n/a')}), batch size {info.get('batch_size', 'n/a')}, at "
                f"most {info.get('epochs', 'n/a')} epochs, mixed precision: "
                f"{'on' if info.get('amp_active') else 'off'}."
            ),
            f"- Dataset version `{info.get('dataset_version', 'n/a')}`, protocol "
            f"{info.get('protocol_version', 'n/a')}, preprocessing "
            f"{info.get('preprocess_version', 'n/a')}, git commit "
            f"`{str(info.get('git_commit', 'n/a'))[:12]}`.",
            f"- Protocol compliant: {'yes' if info.get('protocol_compliant') else 'no'}"
            + (
                f" (deviations: {'; '.join(map(str, info['deviations']))})"
                if info.get("deviations")
                else ""
            )
            + f"; reportable: {'yes' if info.get('reportable') else 'no'}.",
            f"- Started {info.get('started_at', 'n/a')}, finished {info.get('finished_at', 'n/a')}"
            + (
                f"; resumed at {', '.join(map(str, info['resumed_at']))}"
                if info.get("resumed_at")
                else ""
            )
            + ".",
        ]
        if info.get("status") == "failed":
            lines.append(f"- **The run failed:** {info.get('error', 'no error message recorded')}.")
        lines.append("")

    lines += [
        "## What happened during training",
        "",
        "_Sources: `train_log.csv`, `observations/epochs.jsonl`, "
        "`observations/training_summary.json`._",
        "",
    ]
    if info.get("model_type") == "tabular":
        lines += _tabular_training_lines(metrics)
    elif not log and not epochs:
        lines += [
            "No epoch was logged (training has not run or stopped before the first epoch).",
            "",
        ]
    else:
        lines.append(f"{len(log)} epoch(s) are logged in `train_log.csv`.")
        lines.append("")
        lines += [
            "| Epoch | LR | Train loss | Val loss | Val AUC | Improved | Seconds |",
            "| ---: | ---: | ---: | ---: | ---: | :---: | ---: |",
        ]
        improved = {int(e["epoch"]): bool(e.get("improved")) for e in epochs if "epoch" in e}
        for row in log:
            ep = int(float(row["epoch"]))
            mark = "yes" if improved.get(ep) else ("no" if ep in improved else "n/a")
            lines.append(
                f"| {ep} | {_lr(row.get('lr'))} | {_num(row.get('train_loss'))} | "
                f"{_num(row.get('val_loss'))} | {_num(row.get('val_auc'))} | {mark} | "
                f"{_num(row.get('epoch_seconds'), 1)} |"
            )
        lines.append("")
    if summary:
        lines += [
            f"- **Kept checkpoint:** epoch {summary.get('best_epoch', 'n/a')}, validation AUC "
            f"{_num(summary.get('best_val_auc'))}. Rule: "
            f"{summary.get('checkpoint_rule', 'n/a')}.",
            f"- **Why training stopped:** {summary.get('stop_reason', 'n/a')} "
            f"(stopped at epoch {summary.get('stop_epoch', 'n/a')} of at most "
            f"{summary.get('max_epochs', 'n/a')}; patience {summary.get('patience', 'n/a')}).",
            f"- Resumed after an interruption at epoch(s): "
            f"{', '.join(map(str, summary.get('resumed_at_epochs') or [])) or 'never'}.",
            f"- Warnings during training: {summary.get('warnings', 'n/a')}; batches with a "
            f"non-finite loss: {summary.get('non_finite_loss_batches', 'n/a')}.",
            f"- Peak GPU memory in training: {_num(summary.get('peak_gpu_memory_mb'), 0)} MB.",
        ]
        warned = sorted({w for e in epochs for w in e.get("warnings") or []})
        for message in warned:
            lines.append(f"  - warning seen: {message}")
        lines.append("")
    elif info.get("model_type") != "tabular":
        lines += ["`observations/training_summary.json` is not present.", ""]

    if metrics:
        val = (metrics.get("val") or {}).get("image") or {}
        lines += [
            "## After training (validation only)",
            "",
            "_Source: `metrics.json`. Validation numbers use the fixed, uncalibrated 0.5; tau is "
            "chosen in evaluate. Training never opens the test split._",
            "",
            f"- Parameters: {metrics.get('parameter_count', 'n/a')}; training time "
            f"{_duration(metrics.get('training_time_seconds'))}; mean epoch "
            f"{_num(metrics.get('mean_epoch_seconds'), 1)} s.",
            f"- Validation (image level, at 0.5): AUC {_num(val.get('auc_roc'))}, recall "
            f"{_num(val.get('recall'))}, specificity {_num(val.get('specificity'))}, F1 "
            f"{_num(val.get('f1'))}.",
            "",
        ]

    lines += ["## Evaluation", "", "_Source: `evaluation.json`._", ""]
    if not evaluation:
        lines += ["Not yet run (`oscc-ml evaluate` has not processed this run).", ""]
    else:
        tau = evaluation.get("threshold") or {}
        test = evaluation.get("test") or {}
        at_tau = evaluation.get("test_at_tau") or {}
        cm = at_tau.get("confusion_matrix") or {}
        calib = (evaluation.get("calibration") or {}).get("test") or {}
        lines += [
            f"- **Decision threshold tau = {_num(tau.get('threshold'), 6)}**, "
            "chosen on validation: "
            f"{tau.get('rule', 'n/a')} (target recall {_num(tau.get('target_recall'), 2)}; "
            f"validation recall {_num(tau.get('validation_recall'))}, validation F1 "
            f"{_num(tau.get('validation_f1'))}). Inconclusive margin "
            f"{_num(evaluation.get('inconclusive_margin'), 2)}.",
            "- Test predictions: "
            f"{(evaluation.get('test_predictions') or {}).get('source', 'n/a')}.",
            "- Test, image level, at tau (95% CIs resample groups):",
        ]
        for metric in ("auc_roc", "accuracy", "precision", "recall", "specificity", "f1"):
            lines.append(f"  - {metric}: {_ci(test.get(metric))}")
        lines += [
            f"- Confusion matrix at tau: TP {cm.get('tp', 'n/a')}, FP {cm.get('fp', 'n/a')}, "
            f"FN {cm.get('fn', 'n/a')}, TN {cm.get('tn', 'n/a')}.",
            f"- Calibration on test: ECE {_num(calib.get('ece'))}, MCE {_num(calib.get('mce'))}.",
        ]
        for mag, block in sorted((evaluation.get("test_by_magnification") or {}).items()):
            auc = (block or {}).get("auc_roc")
            auc_text = _num(auc.get("estimate") if isinstance(auc, dict) else auc)
            lines.append(
                f"- Magnification {mag}: {block.get('n_images', 'n/a')} test images, "
                f"AUC {auc_text}."
            )
        cost = evaluation.get("cost") or {}
        latency = cost.get("latency_cpu") or {}
        lines += [
            f"- Cost: {_num(cost.get('gflops_per_patch'), 2)} GFLOPs per patch, CPU latency "
            f"{_num(latency.get('mean_ms'), 1)} ms (batch 1).",
            f"- Evaluated at {evaluation.get('evaluated_at', 'n/a')}.",
            "",
        ]
    return lines


def _tabular_training_lines(metrics: dict[str, Any] | None) -> list[str]:
    """Tabular runs have no epochs: the journal shows the grouped-CV tuning instead."""
    tuning = (metrics or {}).get("tuning") or {}
    if not tuning:
        return ["`metrics.json` has no tuning record.", ""]
    lines = [
        f"Tuning: {tuning.get('method', 'n/a')}.",
        "",
        "| Rank | Setting | Mean CV AUC | SD |",
        "| ---: | --- | ---: | ---: |",
    ]
    for row in sorted(tuning.get("cv_results") or [], key=lambda r: r.get("rank", 0)):
        setting = ", ".join(f"{k}={v}" for k, v in sorted((row.get("params") or {}).items()))
        lines.append(
            f"| {row.get('rank')} | {setting} | {_num(row.get('mean_cv_auc'))} | "
            f"{_num(row.get('std_cv_auc'))} |"
        )
    best = ", ".join(f"{k}={v}" for k, v in sorted((tuning.get("best_params") or {}).items()))
    lines += [
        "",
        f"- **Chosen setting:** {best} (highest mean grouped-CV AUC on train, "
        f"{_num(tuning.get('best_mean_cv_auc'))}); refitted on all of train.",
        f"- Features used: {(metrics or {}).get('n_features', 'n/a')}.",
        "",
    ]
    return lines


def write_run_journal(run_dir: Path) -> Path:
    return _write(run_dir / JOURNAL_FILE, run_journal_lines(run_dir))


# --------------------------------------------------------------------------------------------------
# Sweep
# --------------------------------------------------------------------------------------------------


def sweep_journal_lines(runs_dir: Path) -> list[str]:
    chosen = _read_json(runs_dir / SWEEP_DIR / "chosen_lr.json")
    lines = ["# Training journal: shared learning-rate sweep", "", HEADER_NOTE, ""]
    lines += ["_Source: `sweep/chosen_lr.json`._", ""]
    if not chosen:
        return [*lines, "Not yet run (`sweep/chosen_lr.json` is missing).", ""]
    models = chosen.get("models") or []
    grid = chosen.get("lr_grid") or []
    lines += [
        f"Every model in ({', '.join(models)}) was trained for "
        f"{chosen.get('epochs_per_trial', 'n/a')} "
        f"epochs at each learning rate in ({', '.join(_lr(x) for x in grid)}), seed "
        f"{chosen.get('seed', 'n/a')}, dataset `{chosen.get('dataset_version', 'n/a')}`. "
        "Protocol sweep (pretrained, real data): "
        f"{'yes' if chosen.get('protocol_sweep') else 'no'}.",
        "",
        f"**Chosen learning rate: {_lr(chosen.get('chosen_lr'))}.** Rule: "
        f"{chosen.get('selection_rule', 'n/a')}.",
        "",
        "| Rank | LR | Mean val AUC | Decision | Reason |",
        "| ---: | ---: | ---: | --- | --- |",
    ]
    for row in chosen.get("lr_decisions") or []:
        lines.append(
            f"| {row.get('rank')} | {_lr(row.get('lr'))} | {_num(row.get('mean_val_auc'))} | "
            f"{row.get('decision')} | {row.get('reason')} |"
        )
    lines += ["", "Validation AUC per model and learning rate:", ""]
    lines += [
        "| LR | " + " | ".join(models) + " |",
        "| ---: |" + " ---: |" * len(models),
    ]
    for lr, by_model in (chosen.get("val_auc_table") or {}).items():
        lines.append(f"| {lr} | " + " | ".join(_num(by_model.get(m)) for m in models) + " |")
    best = chosen.get("best_lr_per_model") or {}
    if best:
        lines += [
            "",
            "Each model's own best LR (for information; the shared LR above is what training "
            "uses): " + ", ".join(f"{m} {_lr(v)}" for m, v in best.items()) + ".",
        ]
    lines.append("")
    return lines


def write_sweep_journal(runs_dir: Path) -> Path:
    return _write(runs_dir / SWEEP_DIR / JOURNAL_FILE, sweep_journal_lines(runs_dir))


# --------------------------------------------------------------------------------------------------
# Whole pipeline
# --------------------------------------------------------------------------------------------------


def pipeline_journal_lines(runs_dir: Path) -> list[str]:
    decisions = _read_jsonl(runs_dir / "decisions.jsonl")
    chosen = _read_json(runs_dir / SWEEP_DIR / "chosen_lr.json")
    lines = ["# Training journal: whole pipeline", "", HEADER_NOTE, ""]

    lines += [
        "## Steps",
        "",
        "_Sources: `sweep/chosen_lr.json`, `*/run_info.json`, `*/evaluation.json`._",
        "",
    ]
    lines.append(
        f"1. Sweep: chosen LR {_lr(chosen.get('chosen_lr'))}."
        if chosen
        else "1. Sweep: not yet run."
    )
    runs = []
    for info_path in sorted(runs_dir.glob("*/run_info.json")):
        info = _read_json(info_path) or {}
        if info.get("purpose") == "train":
            runs.append((info_path.parent, info))
    if not runs:
        lines.append("2. Training: not yet run.")
    else:
        lines.append(f"2. Training: {len(runs)} run(s).")
        for run_dir, info in runs:
            lines.append(
                f"   - `{run_dir.name}`: {info.get('architecture')} seed {info.get('seed')}, "
                f"status {info.get('status')}; journal `{run_dir.name}/{JOURNAL_FILE}`."
            )
    evaluated: list[tuple[Path, dict[str, Any]]] = []
    for run_dir, _ in runs:
        ev = _read_json(run_dir / "evaluation.json")
        if ev:
            evaluated.append((run_dir, ev))
    if not evaluated:
        lines.append("3. Evaluation: not yet run.")
    else:
        lines += [
            f"3. Evaluation: {len(evaluated)} run(s) evaluated on the test split.",
            "",
            "| Run | Model | tau | Test AUC (95% CI) | Recall at tau (95% CI) |",
            "| --- | --- | ---: | --- | --- |",
        ]
        for run_dir, ev in evaluated:
            test = ev.get("test") or {}
            lines.append(
                f"| `{run_dir.name}` | {ev.get('architecture')} | "
                f"{_num((ev.get('threshold') or {}).get('threshold'), 6)} | "
                f"{_ci(test.get('auc_roc'))} | {_ci(test.get('recall'))} |"
            )
    lines.append("")

    lines += ["## Decisions and their reasons", "", "_Source: `decisions.jsonl`._", ""]
    if not decisions:
        lines += ["No decision recorded yet.", ""]
    else:
        for entry in decisions:
            reason = entry.get("reason") or entry.get("rule")
            text = f"- [{entry.get('step')}] {entry.get('decision')}"
            if reason:
                text += f". Why: {reason}"
            if entry.get("evidence"):
                text += f" (evidence: `{entry['evidence']}`)"
            lines.append(text)
        lines.append("")
    return lines


def write_pipeline_journal(runs_dir: Path) -> Path:
    return _write(runs_dir / JOURNAL_FILE, pipeline_journal_lines(runs_dir))


def safely(writer: Any, *args: Any) -> None:
    """Write a journal without ever failing the training step that called it."""
    try:
        writer(*args)
    except Exception:  # a journal must never cost a multi-hour run
        logger.exception("could not write %s", JOURNAL_FILE)
