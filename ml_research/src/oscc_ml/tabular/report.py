"""``docs/results/TABULAR_RESULTS.md`` generated ONLY from saved files: the tabular run folders,
``extraction.json`` and ``shortcut_check.json``. Nothing is typed by hand."""

from __future__ import annotations

from pathlib import Path
from typing import Any

import pandas as pd

from oscc_ml.catalog import DISPLAY_NAME, TABULAR_ARCHITECTURES
from oscc_ml.utils.io import read_json

METRICS = ("auc_roc", "accuracy", "precision", "recall", "specificity", "f1")


def _ci(entry: dict[str, Any] | None) -> str:
    if not entry or entry.get("estimate") is None:
        return "n/a"
    low, high = entry.get("ci_low"), entry.get("ci_high")
    if low is None or high is None:
        return f"{entry['estimate']:.3f}"
    return f"{entry['estimate']:.3f} [{low:.3f}, {high:.3f}]"


def _f(value: Any, fmt: str = ".3f") -> str:
    return "n/a" if value is None else format(value, fmt)


def latest_runs(runs_dir: Path, purpose: str) -> dict[str, Path]:
    chosen: dict[str, Path] = {}
    for info_path in sorted(runs_dir.glob("*/run_info.json")):
        info = read_json(info_path)
        if (
            info.get("model_type") == "tabular"
            and info.get("purpose") == purpose
            and info.get("status") == "completed"
            and (info_path.parent / "evaluation.json").is_file()
        ):
            chosen[str(info["architecture"])] = info_path.parent  # later folders win
    return chosen


def render(runs_dir: Path, features_dir: Path, checks_dir: Path) -> str:
    extraction = read_json(features_dir / "extraction.json")
    main = latest_runs(runs_dir, "train")
    ablation = latest_runs(runs_dir, "ablation")
    lines = [
        "# Tabular classifiers: FYP-I results",
        "",
        "_Generated by `oscc-ml tabular-report` from the run folders, `extraction.json` and "
        "`shortcut_check.json`; do not edit by hand. Seed 42, one run per model (FYP-I baseline)._",
        "",
        "## Dataset",
        "",
        f"- Table `{extraction['features_file']}`, SHA-256 `{extraction['features_sha256']}`, "
        f"features version `{extraction['tabular_features_version']}`, {extraction['n_images']} "
        f"images, {extraction['n_feature_columns']} feature columns (incl. 2 mask diagnostics "
        "not used by the models).",
        "- Split (from the manifest): "
        + ", ".join(
            f"{s} {c['images']} ({c['non_oscc']} non-OSCC / {c['oscc']} OSCC)"
            for s, c in extraction["counts"].items()
        )
        + ".",
        f"- Manifest SHA-256 `{extraction['manifest_sha256']}`; tissue-mask fallbacks: "
        f"{extraction['n_tissue_mask_fallback']}; extraction {extraction['seconds_per_image']} s "
        "per image on the laptop CPU.",
        "",
        "## Test results (image level, tau from validation, 95% grouped-bootstrap CIs)",
        "",
        "| Model | Run | tau | " + " | ".join(METRICS) + " |",
        "| --- | --- | ---: | " + " | ".join("---" for _ in METRICS) + " |",
    ]
    for arch in TABULAR_ARCHITECTURES:
        run = main.get(arch)
        if run is None:
            lines.append(
                f"| {DISPLAY_NAME[arch]} | not yet run |  | "
                + " | ".join("" for _ in METRICS)
                + " |"
            )
            continue
        ev = read_json(run / "evaluation.json")
        lines.append(
            f"| {DISPLAY_NAME[arch]} | `{run.name}` | {ev['threshold']['threshold']:.4f} | "
            + " | ".join(_ci(ev["test"].get(m)) for m in METRICS)
            + " |"
        )
    lines += [
        "",
        "## Per magnification (test, at tau; point estimates)",
        "",
        "| Model | Magnification | n | AUC | Recall | Specificity |",
        "| --- | --- | ---: | ---: | ---: | ---: |",
    ]
    for arch, run in main.items():
        ev = read_json(run / "evaluation.json")
        for mag, block in sorted(ev["test_by_magnification"].items()):
            lines.append(
                f"| {DISPLAY_NAME[arch]} | {mag} | {block['n_images']} | "
                f"{_f(block.get('auc_roc'))} "
                f"| {_f(block.get('recall'))} | {_f(block.get('specificity'))} |"
            )
    lines += [
        "",
        "## Tuning, calibration, errors and cost",
        "",
        "| Model | Chosen setting (grouped CV on train) | Mean CV AUC | ECE (test) "
        "| TP / FP / FN / TN | Learnt numbers | CPU latency per row (ms) |",
        "| --- | --- | ---: | ---: | --- | ---: | ---: |",
    ]
    for arch, run in main.items():
        ev = read_json(run / "evaluation.json")
        metrics = read_json(run / "metrics.json")
        cm = ev["test_at_tau"]["confusion_matrix"]
        best = ", ".join(f"{k}={v}" for k, v in sorted(metrics["tuning"]["best_params"].items()))
        lines.append(
            f"| {DISPLAY_NAME[arch]} | {best} | {metrics['tuning']['best_mean_cv_auc']:.3f} | "
            f"{ev['calibration']['test']['ece']:.3f} | {cm['tp']} / {cm['fp']} / {cm['fn']} / "
            f"{cm['tn']} | {ev['cost']['parameter_count']} | "
            f"{ev['cost']['latency_cpu']['mean_ms']:.2f} |"
        )
    lines += [
        "",
        "## Permutation importance (validation, drop in ROC AUC; top 10 per model)",
        "",
    ]
    for arch, run in main.items():
        imp = pd.read_csv(run / "permutation_importance_val.csv").head(10)
        lines.append(
            f"- **{DISPLAY_NAME[arch]}:** "
            + ", ".join(
                f"`{r.feature}` {r.importance_mean:.3f}" for r in imp.itertuples(index=False)
            )
        )
    lines += [
        "",
        "## Ablation: + magnification (`is_400x`)",
        "",
        "| Model | Test AUC without | Test AUC with magnification |",
        "| --- | --- | --- |",
    ]
    for arch in TABULAR_ARCHITECTURES:
        a, b = main.get(arch), ablation.get(arch)
        lines.append(
            f"| {DISPLAY_NAME[arch]} | "
            f"{_ci(read_json(a / 'evaluation.json')['test']['auc_roc']) if a else 'not yet run'} | "
            f"{_ci(read_json(b / 'evaluation.json')['test']['auc_roc']) if b else 'not yet run'} |"
        )
    check_path = checks_dir / "shortcut_check.json"
    lines += ["", "## Shortcut check (non-pathology cues)", ""]
    if not check_path.is_file():
        lines.append("Not yet run (`oscc-ml tabular-shortcut`).")
    else:
        check = read_json(check_path)
        lines += [
            f"Rule fixed before the run: {check['rule']}. {check['model']}. CIs: {check['ci']}.",
            "",
            "| Baseline | Test AUC [95% CI] | Verdict |",
            "| --- | --- | --- |",
        ]
        for name, block in check["baselines"].items():
            lines.append(f"| {name} | {_ci(block['test_auc'])} | {block['verdict']} |")
        lines += ["", f"**Overall:** {check['overall_verdict']}."]
    lines.append("")
    return "\n".join(lines)


def write_report(runs_dir: Path, features_dir: Path, checks_dir: Path, out: Path) -> Path:
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(runs_dir, features_dir, checks_dir), encoding="utf-8")
    return out
