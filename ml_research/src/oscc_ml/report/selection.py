"""``MODEL_SELECTION.md``: the SDS selection rule applied to every evaluated model, generated ONLY
from run folders and ``comparisons.json``. Every number below is read from a file; the sentences
around them are fixed templates.

SDS Appendix A (``docs/SDS.md`` "Model selection"): "Highest test AUC-ROC, with recall as the
tie-breaker; the administrator activates the selected version."
"""

from __future__ import annotations

from collections import Counter
from pathlib import Path
from typing import Any

from oscc_ml.catalog import DISPLAY_NAME, FAMILY
from oscc_ml.utils.io import read_json

SDS_RULE = (
    "Highest test AUC-ROC, with recall as the tie-breaker; the administrator activates the "
    "selected version."
)
TIE_DECIMALS = 3  # AUCs equal to 3 decimals (the precision reported) count as a tie


def _ci(entry: dict[str, Any] | None) -> str:
    if not entry or entry.get("estimate") is None:
        return "n/a"
    low, high = entry.get("ci_low"), entry.get("ci_high")
    if low is None or high is None:
        return f"{entry['estimate']:.3f}"
    return f"{entry['estimate']:.3f} [{low:.3f}, {high:.3f}]"


def _f(value: Any, fmt: str = ".3f") -> str:
    return "n/a" if value is None else format(value, fmt)


def rank(evaluations: dict[str, dict[str, Any]]) -> list[str]:
    """Architectures ordered by the SDS rule: test AUC (rounded to TIE_DECIMALS) desc, then test
    recall desc, then name (deterministic)."""

    def key(arch: str) -> tuple[float, float, str]:
        test = evaluations[arch]["test"]
        auc = round(float(test["auc_roc"]["estimate"]), TIE_DECIMALS)
        recall = float(test["recall"]["estimate"] or 0.0)
        return (-auc, -recall, arch)

    return sorted(evaluations, key=key)


def _stability(run_dir: Path, info: dict[str, Any]) -> str:
    if info.get("model_type") == "tabular":
        metrics = read_json(run_dir / "metrics.json")
        best = max(metrics["tuning"]["cv_results"], key=lambda r: float(r["mean_cv_auc"]))
        return (
            f"chosen setting: grouped-CV AUC {best['mean_cv_auc']:.3f} ± {best['std_cv_auc']:.3f} "
            "(SD across the CV folds)"
        )
    path = run_dir / "observations" / "training_summary.json"
    if not path.is_file():
        return "no observation record"
    s = read_json(path)
    return (
        f"best epoch {s.get('best_epoch')} of {s.get('epochs_run')} run; {s.get('stop_reason')}; "
        f"non-finite loss batches {s.get('non_finite_loss_batches')}; warnings "
        f"{s.get('warnings')}; resumed at {s.get('resumed_at_epochs') or 'never'}"
    )


def _pair(pairs: list[dict[str, Any]], a: str, b: str) -> tuple[dict[str, Any] | None, int]:
    """The comparison of a vs b and the sign that makes the delta read 'a minus b'."""
    for pair in pairs:
        if pair["a"] == a and pair["b"] == b:
            return pair, 1
        if pair["a"] == b and pair["b"] == a:
            return pair, -1
    return None, 1


def render(
    records: dict[str, tuple[Path, dict[str, Any], dict[str, Any]]],
    comparisons: dict[str, Any] | None,
    *,
    seed: int,
    synthetic: bool,
    missing: list[str],
) -> str:
    """``records``: architecture -> (run folder, run_info, evaluation)."""
    evaluations = {arch: ev for arch, (_, _, ev) in records.items()}
    order = rank(evaluations)
    chosen = order[0]
    banner = (
        [
            "> **SYNTHETIC — not real results.** Built from synthetic test runs.",
            "",
        ]
        if synthetic
        else []
    )
    pairs = ((comparisons or {}).get("seeds") or {}).get(str(seed), [])
    lines = [
        "# Model selection (FYP-I baseline)",
        "",
        *banner,
        "_Generated by `oscc-ml report` from run folders and `comparisons.json` only; do not edit "
        "by hand._",
        "",
        "## Rule",
        "",
        f'- **SDS Appendix A:** "{SDS_RULE}"',
        f"- Applied as: rank by test AUC-ROC rounded to {TIE_DECIMALS} decimals (higher first); "
        "ties broken by test recall at each model's own tau (higher first).",
        "- **Optimism caveat:** the winner is picked on the test set, so its test AUC is an "
        "optimistic estimate of performance on new data (selection on the same data that is "
        "reported). The split is grouped by image similarity, not by patient (errata E7), which "
        "can also make every test estimate optimistic.",
        f"- **One seed ({seed}) in FYP-I.** These are baselines. The final choice is made in "
        "FYP-II with 3 seeds (42, 43, 44) and the paired tests below.",
        "",
        f"**Selected under the rule: {DISPLAY_NAME.get(chosen, chosen)}** "
        f"(test AUC {_ci(evaluations[chosen]['test']['auc_roc'])}, recall "
        f"{_ci(evaluations[chosen]['test']['recall'])}).",
        "",
    ]
    if missing:
        lines += [
            "Not yet run (not part of this selection): "
            + ", ".join(DISPLAY_NAME.get(a, a) for a in missing)
            + ".",
            "",
        ]
    lines += [
        "## Performance (test, image level, at each model's tau; 95% grouped-bootstrap CIs)",
        "",
        "| Rank | Model | Family | AUC-ROC | Recall | Specificity | Precision | F1 | Accuracy "
        "| tau |",
        "| ---: | --- | --- | --- | --- | --- | --- | --- | --- | ---: |",
    ]
    for i, arch in enumerate(order, start=1):
        t = evaluations[arch]["test"]
        lines.append(
            f"| {i} | {DISPLAY_NAME.get(arch, arch)} | {FAMILY.get(arch, '?')} "
            f"| {_ci(t['auc_roc'])} "
            f"| {_ci(t['recall'])} | {_ci(t['specificity'])} | {_ci(t['precision'])} "
            f"| {_ci(t['f1'])} | {_ci(t['accuracy'])} | "
            f"{evaluations[arch]['threshold']['threshold']:.3f} |"
        )
    lines += [
        "",
        "## Paired comparisons with the selected model (same test images)",
        "",
    ]
    if not pairs:
        lines.append("No `comparisons.json` for this seed (fewer than two evaluated models).")
    else:
        lines += [
            f"ΔAUC = selected minus other; paired bootstrap over groups; McNemar exact at each "
            f"model's tau; Holm-adjusted over all {len(pairs)} pairs.",
            "",
            "| Other model | ΔAUC [95% CI] | p (Holm) | McNemar b / c | McNemar p (Holm) |",
            "| --- | --- | ---: | --- | ---: |",
        ]
        for arch in order[1:]:
            pair, sign = _pair(pairs, chosen, arch)
            if pair is None:
                lines.append(f"| {DISPLAY_NAME.get(arch, arch)} | not compared |  |  |  |")
                continue
            d = pair["delta_auc"]
            lo, hi = d.get("ci_low"), d.get("ci_high")
            ci = (
                "n/a"
                if lo is None or hi is None
                else f"[{min(sign * lo, sign * hi):+.3f}, {max(sign * lo, sign * hi):+.3f}]"
            )
            m = pair["mcnemar"]
            b, c = m["b_only_a_correct"], m["c_only_b_correct"]
            if sign < 0:
                b, c = c, b
            lines.append(
                f"| {DISPLAY_NAME.get(arch, arch)} | {sign * d['estimate']:+.3f} {ci} | "
                f"{d['p_holm']:.3g} | {b} / {c} | {m['p_holm']:.3g} |"
            )
    lines += [
        "",
        "## Per magnification (test, at tau; point estimates)",
        "",
        "| Model | Magnification | n | AUC | Recall | Specificity |",
        "| --- | --- | ---: | ---: | ---: | ---: |",
    ]
    for arch in order:
        for mag, block in sorted(evaluations[arch].get("test_by_magnification", {}).items()):
            lines.append(
                f"| {DISPLAY_NAME.get(arch, arch)} | {mag} | {block['n_images']} | "
                f"{_f(block.get('auc_roc'))} | {_f(block.get('recall'))} | "
                f"{_f(block.get('specificity'))} |"
            )
    lines += [
        "",
        "## Calibration, errors, stability and cost",
        "",
        "| Model | ECE val / test | FP / FN at tau | FN by magnification | Training stability "
        "| Params | CPU latency (ms) |",
        "| --- | --- | --- | --- | --- | ---: | ---: |",
    ]
    fn_sets: dict[str, set[str]] = {}
    for arch in order:
        run_dir, info, ev = records[arch]
        cal = ev.get("calibration", {})
        errors = ev["test_at_tau"]
        fn_mag = Counter(str(r.get("magnification")) for r in errors["false_negatives"])
        fn_sets[arch] = {str(r["image_id"]) for r in errors["false_negatives"]}
        cost = ev["cost"]
        lines.append(
            f"| {DISPLAY_NAME.get(arch, arch)} | {_f(cal.get('validation', {}).get('ece'))} / "
            f"{_f(cal.get('test', {}).get('ece'))} | {errors['confusion_matrix']['fp']} / "
            f"{errors['confusion_matrix']['fn']} | "
            + (", ".join(f"{k} {v}" for k, v in sorted(fn_mag.items())) or "none")
            + f" | {_stability(run_dir, info)} | {cost.get('parameter_count')} | "
            f"{_f(cost.get('latency_cpu', {}).get('mean_ms'), '.2f')} |"
        )
    missed_by_all = set.intersection(*fn_sets.values()) if fn_sets else set()
    lines += [
        "",
        f"OSCC test images missed by **every** model at its tau: {len(missed_by_all)}"
        + (f" ({', '.join(sorted(missed_by_all)[:20])})" if missed_by_all else "")
        + ". These are candidates for a pathologist's review (label noise or hard cases).",
        "",
        "Latency: image models are timed per 224 px patch at batch 1; tabular models per feature "
        "row (feature extraction is reported separately in the tabular results). GFLOPs and the "
        "accuracy-vs-cost figure are in the results package.",
        "",
        "## Why the other models were not selected",
        "",
    ]
    top = evaluations[chosen]["test"]
    for arch in order[1:]:
        t = evaluations[arch]["test"]
        pair, sign = _pair(pairs, chosen, arch)
        tied = round(t["auc_roc"]["estimate"], TIE_DECIMALS) == round(
            top["auc_roc"]["estimate"], TIE_DECIMALS
        )
        reason = (
            f"its test AUC ties with the selected model at {TIE_DECIMALS} decimals and its recall "
            f"is lower ({t['recall']['estimate']:.3f} vs {top['recall']['estimate']:.3f})"
            if tied
            else f"its test AUC {t['auc_roc']['estimate']:.3f} is below the selected model's "
            f"{top['auc_roc']['estimate']:.3f}"
        )
        if pair is not None:
            d = pair["delta_auc"]
            significant = d["p_holm"] < 0.05
            reason += (
                f"; the paired difference {sign * d['estimate']:+.3f} has Holm p = "
                f"{d['p_holm']:.3g}, so it is "
                + ("statistically significant" if significant else "NOT statistically significant")
                + " at 0.05"
                + ("" if significant else " (with one seed, the two cannot be told apart)")
            )
        lines.append(f"- **{DISPLAY_NAME.get(arch, arch)}:** {reason}.")
    lines.append("")
    return "\n".join(lines)
