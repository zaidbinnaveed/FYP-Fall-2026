/**
 * Types shared by the screens and the API layer. The mock implementation (`mock.ts`) returns
 * fixtures; a real HTTP client implementing `Api` can replace it later without touching screens.
 */
import type { Outcome } from '../domain/outcome';

export type ModelFamily = 'CNN' | 'ViT' | 'Tabular' | 'Demo';
/** SDS `model_versions.status`. */
export type RegistryStatus = 'registered' | 'validated' | 'active' | 'retired';
/** SDS `hospitals.facility_type`. */
export type FacilityType = 'oncology_center' | 'ent_clinic' | 'general_hospital_oncology_ward';
/** Subset of SDS reminder status used by the demo. */
export type ReminderStatus = 'scheduled' | 'taken' | 'skipped' | 'snoozed' | 'missed';

export interface DemoUser {
  name: string;
  email: string;
}

export interface RegistryModel {
  /** Key shared with the research report (`architecture` in summary.json). */
  architecture: string;
  name: string;
  family: ModelFamily;
  version: string;
  status: RegistryStatus;
  input: 'image' | 'tabular' | 'none';
}

/**
 * One row of `ml_research/runs/report/summary.json` (written by `oscc-ml report`). Rows with
 * `status: "not yet run"` carry only architecture, model and status.
 */
export interface BenchmarkRow {
  architecture: string;
  model: string;
  status: string;
  family?: string | undefined;
  auc_roc_estimate?: number | null | undefined;
  auc_roc_ci_low?: number | null | undefined;
  auc_roc_ci_high?: number | null | undefined;
  recall_estimate?: number | null | undefined;
  recall_ci_low?: number | null | undefined;
  recall_ci_high?: number | null | undefined;
  specificity_estimate?: number | null | undefined;
  specificity_ci_low?: number | null | undefined;
  specificity_ci_high?: number | null | undefined;
  f1_estimate?: number | null | undefined;
  f1_ci_low?: number | null | undefined;
  f1_ci_high?: number | null | undefined;
  threshold?: number | null | undefined;
  parameter_count?: number | null | undefined;
  cpu_latency_mean_ms?: number | null | undefined;
}

export type DataSource = 'report' | 'sample';

export interface Benchmark {
  source: DataSource;
  generatedAt: string | null;
  rows: BenchmarkRow[];
  notes: string[];
}

export interface SampleCase {
  id: string;
  title: string;
  description: string;
}

export interface ScreeningResult {
  caseId: string;
  caseTitle: string;
  probability: number;
  tau: number;
  margin: number;
  modelVersion: string;
  outcome: Outcome;
}

export interface ComparisonRow {
  architecture: string;
  name: string;
  family: ModelFamily;
  /** `null` for models that cannot score an image (tabular). */
  probability: number | null;
  tau: number | null;
  outcome: Outcome | null;
}

export interface Hospital {
  id: string;
  name: string;
  facilityType: FacilityType;
  address: string;
  distanceKm: number;
}

export interface PlanEntry {
  id: string;
  medicine: string;
  /** Free text exactly as the user typed it from the prescription. Never generated by the app. */
  doseAsEntered: string;
  times: string[];
}

export interface Reminder {
  id: string;
  entryId: string;
  time: string;
  status: ReminderStatus;
}

export interface Adherence {
  taken: number;
  total: number;
}

export interface Api {
  login(email: string, password: string): Promise<DemoUser>;
  register(name: string, email: string, password: string): Promise<DemoUser>;
  listSampleCases(): Promise<SampleCase[]>;
  /** Deterministic demo rule: the same file name always maps to the same sample case. */
  caseForFileName(fileName: string): string;
  getScreeningResult(caseId: string): Promise<ScreeningResult | null>;
  getComparison(caseId: string): Promise<ComparisonRow[]>;
  getBenchmark(): Promise<Benchmark>;
  getRegistry(): Promise<RegistryModel[]>;
  getHospitals(): Promise<Hospital[]>;
  getTreatmentPlan(): Promise<PlanEntry[]>;
  getReminders(): Promise<Reminder[]>;
  getAdherence(): Promise<Adherence>;
}
